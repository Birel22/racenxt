import json, re
d = json.load(open('/tmp/louis.json'))
A = "https://birel22.github.io/louis-calendar/"
q = lambda s: "null" if s is None else "'" + str(s).replace("'", "''") + "'"
L = lambda v: v["en"] if isinstance(v, dict) else v

SERIES = [
 ("wec","FIA World Endurance Championship","WEC","https://www.fiawec.com","https://plus.fiawec.com/en", A+"lg-lm.png"),
 ("elms","European Le Mans Series","ELMS","https://www.europeanlemansseries.com","https://plus.fiawec.com/en", A+"lg-elms.png"),
 ("alms","Asian Le Mans Series","ALMS","https://www.asianlemansseries.com","https://www.youtube.com/@AsianLeMansSeries", A+"lg-alms.png"),
 ("imsa","IMSA WeatherTech SportsCar Championship","IMSA","https://www.imsa.com","https://www.youtube.com/IMSAOfficial", A+"lg-imsa.png"),
 ("gtwc","GT World Challenge","GTWC","https://www.gt-world-challenge.com",None,None),
 ("lmc","Michelin Le Mans Cup","LMC","https://www.lemanscup.com",None,None),
 ("f2","FIA Formula 2 Championship","F2","https://www.fiaformula2.com",None,None),
 ("f3","FIA Formula 3 Championship","F3","https://www.fiaformula3.com",None,None),
]
TZ = {"jerez":"Europe/Madrid","daytona":"America/New_York","portimao-alms":"Europe/Lisbon","barcelona":"Europe/Madrid","sebring":"America/New_York","longbeach":"America/Los_Angeles","laguna":"America/Los_Angeles","detroit":"America/Detroit","lemans":"Europe/Paris","watkins":"America/New_York","imola":"Europe/Rome","roadamerica":"America/Chicago","spa":"Europe/Brussels","silverstone":"Europe/London","indy":"America/Indiana/Indianapolis","petitlemans":"America/New_York","portimao-elms":"Europe/Lisbon"}
CC = {"Spain":"ES","USA":"US","Portugal":"PT","France":"FR","Italy":"IT","Belgium":"BE","United Kingdom":"GB"}
SMAP = {"alms":"alms","elms":"elms","imsa":"imsa","lm":"wec"}
out = ["-- Seed: launch championships + Louis Delétraz (generated by make_seed.py)", "begin;"]
for s in SERIES:
    out.append(f"insert into public.series (slug,name,short_name,website_url,watch_url,logo_url) values ({','.join(q(x) for x in s)}) on conflict (slug) do nothing;")

venues = {}
rounds = {}
for ev in d["EVENTS"]:
    where = L(ev["where"]); parts = [p.strip() for p in where.split(" · ")]
    name = parts[0]; city = parts[1] if len(parts) > 1 else None
    country = L(ev["country"])
    key = name
    if key not in venues:
        venues[key] = True
        out.append(f"insert into public.venues (name,city,country,country_code,timezone) select {q(name)},{q(city)},{q(country)},{q(CC.get(country))},{q(TZ[ev['id']])} where not exists (select 1 from public.venues where name={q(name)});")
for ev in d["EVENTS"]:
    s = SMAP[ev["series"]]; yr = int(ev["s"][:4])
    if s == "wec":
        ext, rnd = f"wec-{yr}-lemans", None
    else:
        rounds[s] = rounds.get(s, 0) + 1; rnd = rounds[s]; ext = f"{s}-{yr}-r{rnd}"
    name = L(ev["name"]); vname = L(ev["where"]).split(" · ")[0].strip()
    note = L(ev.get("note")) if ev.get("note") else None
    out.append(f"insert into public.events (series_id,ext_key,year,round,venue_id,name,start_date,end_date,duration_label,note) "
               f"select (select id from public.series where slug={q(s)}),{q(ext)},{yr},{rnd if rnd else 'null'},(select id from public.venues where name={q(vname)}),{q(name)},{q(ev['s'])},{q(ev['e'])},{q(ev.get('dur'))},{q(note)} "
               f"on conflict (ext_key) do nothing;")
    tt = d["TIMETABLES"].get(ev["id"])
    if tt:
        out.append(f"delete from public.sessions where event_id=(select id from public.events where ext_key={q(ext)});")
        for x in tt["sessions"]:
            lab = L(x["label"]); low = lab.lower()
            typ = "race" if low.startswith("race") else "qualifying" if "quali" in low else "practice" if "practice" in low else "warmup" if "warm" in low else "other"
            out.append(f"insert into public.sessions (event_id,type,label,local_start,duration_min) values ((select id from public.events where ext_key={q(ext)}),{q(typ)},{q(lab)},{q(x['date']+' '+x['time'])},{int(x['min'])});")

# Vehicles (approved catalogue)
for key, car in d["CARS"].items():
    if key == "oreca-alms": continue  # same car as oreca-elms
    nm = "ORECA 07" if key.startswith("oreca") else car["name"]
    cat = "LMP2" if key.startswith("oreca") else "GTP / Hypercar"
    specs = json.dumps([{"label": L(a), "value": L(b)} for a, b in car["specs"]])
    out.append(f"insert into public.vehicles (name,manufacturer,category,specs,photo_url,status) select {q(nm)},{q('ORECA' if key.startswith('oreca') else 'Cadillac')},{q(cat)},{q(specs)}::jsonb,{q(A+car['img'])},'approved' where not exists (select 1 from public.vehicles where name={q(nm)});")

# Profile
socials = {"instagram":"https://www.instagram.com/louisdeletraz/","facebook":"https://www.facebook.com/l.deletraz/","x":"https://x.com/LouisDeletraz","youtube":"https://www.youtube.com/@LouisDel%C3%A9traz-h7t","website":"https://louisdeletraz.com"}
out.append(f"insert into public.profiles (slug,display_name,first_name,photo_url,hero_url,logo_url,socials,published) values ('louis','Louis Delétraz','Louis',{q(A+'car.jpg')},{q(A+'car.jpg')},{q(A+'logo.png')},{q(json.dumps(socials))}::jsonb,true) on conflict (slug) do nothing;")
out.append("insert into public.subscriptions (profile_id,status,provider) select id,'active','manual' from public.profiles where slug='louis' on conflict (profile_id) do nothing;")
# Entries
T = d["TEAM"]
COLORS = {"imsa":"#E8352F","elms":"#F2D30F","alms":"#5FCF6E","wec":"#FF9A1F"}
ENT = [("alms","alms","ORECA 07"),("imsa","imsa","Cadillac V-Series.R"),("elms","elms","ORECA 07"),("wec","lm","ORECA 07")]
for s, tk, veh in ENT:
    t = T[tk]; mates = "{" + ",".join('"'+m+'"' for m in t["mates"]) + "}"
    cat = "LMP2" if veh == "ORECA 07" else "GTP"
    out.append(f"insert into public.entries (profile_id,series_id,year,team,car_number,category,vehicle_id,teammates,color) select (select id from public.profiles where slug='louis'),(select id from public.series where slug={q(s)}),2027,{q(t['team'])},{q(t['num'])},{q(cat)},(select id from public.vehicles where name={q(veh)}),{q(mates)},{q(COLORS[s])} on conflict (profile_id,series_id,year) do nothing;")
# Sponsors
SP = [("Cadillac","cadillac.png","https://www.cadillac.com/racing",0),("AO Racing","ao.png","https://aoracing.com",1),("Conextivity","conextivity.png","https://conextivity.com",2)]
for n, f, link, i in SP:
    out.append(f"insert into public.sponsors (profile_id,name,logo_original_url,logo_white_url,display,link_url,sort) select id,{q(n)},{q(A+f)},{q(A+f)},'white',{q(link)},{i} from public.profiles where slug='louis' and not exists (select 1 from public.sponsors s join public.profiles p on p.id=s.profile_id where p.slug='louis' and s.name={q(n)});")
out.append("commit;")
open('/home/claude/racenxt/supabase/seed/seed.sql','w').write("\n".join(out)+"\n")
print(len(out), "lines")
